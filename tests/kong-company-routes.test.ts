import test from "node:test";
import assert from "node:assert/strict";
import express from "express";
import { createAgentCouncil } from "../server/agent-council";
import { emptyCouncilState } from "../shared/agent-council";
import { registerAgentCouncilRoutes } from "../server/agent-council-routes";

test("real council routes isolate KONG owner writes and strip KONG state for members", async t => {
  const state = emptyCouncilState();
  state.kongCompany.orders.push({ id: "private-order", text: "Owner private request", createdAt: new Date().toISOString(), assignees: [] });
  state.kongObservedAt = new Date().toISOString();
  state.kongLastStatuses["kong:venues"] = { state: "offline", label: "Fixture" };
  state.kongLastStatuses["kong:whatsapp_reader"] = { state: "checking", label: "Owner-only reader evidence" };
  state.kongEvidenceAt["kong:whatsapp_reader"] = new Date().toISOString();
  let raw = JSON.stringify(state);
  let cycles = 0;
  const council = createAgentCouncil({ now: () => Date.now(), userId: () => "owner", readState: async () => raw, writeState: async value => { raw = value; }, collect: async () => { cycles++; return {}; }, submitProposal: async () => "fixture", getPendingActionStatus: async () => null, fetchLatestRelease: async () => null, log: () => {} });
  const app = express(); app.use(express.json());
  registerAgentCouncilRoutes(app, { council, requestUserId: req => String(req.headers["x-test-user"] || "member"), ownerUserId: () => "owner", enabled: () => true });
  const server = app.listen(0, "127.0.0.1");
  await new Promise<void>(resolve => server.once("listening", resolve));
  t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
  const address = server.address(); assert.ok(address && typeof address === "object");
  const base = `http://127.0.0.1:${address.port}`;
  const request = (url: string, user: string, body?: unknown) => fetch(base + url, { method: body === undefined ? "GET" : "POST", headers: { "content-type": "application/json", "x-test-user": user }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const member = await request("/api/agent-council/state", "member");
  assert.equal(member.status, 200);
  assert.equal(member.headers.get("cache-control"), "no-store");
  const memberView = await member.json();
  assert.deepEqual(memberView.kongCompany.orders, []);
  assert.deepEqual(memberView.kongLastStatuses, {});
  assert.deepEqual(memberView.kongEvidenceAt, {});
  assert.equal(JSON.stringify(memberView).includes("Owner-only reader evidence"), false);
  assert.equal(JSON.stringify(memberView).includes("Owner private request"), false);
  assert.equal((await (await request("/api/agent-council/state", "owner")).json()).kongCompany.orders[0].id, "private-order");
  assert.equal((await request("/api/agent-company/orders", "member", { company: "kong", text: "Reject me" })).status, 403);
  assert.equal((await request("/api/agent-company/orders/private-order/done", "member", { company: "kong" })).status, 403);
  assert.equal((await request("/api/agent-council/run", "member", {})).status, 403);
  assert.equal(cycles, 0);
  assert.equal((await request("/api/agent-company/orders", "owner", { company: "typo", text: "Invalid scope" })).status, 400);
  const created = await request("/api/agent-company/orders", "owner", { company: "kong", text: "Review venues" });
  assert.equal(created.status, 200);
  const order = (await created.json()).order;
  assert.equal((await council.load()).company.orders.length, 0);
  assert.equal((await request(`/api/agent-company/orders/${order.id}/done`, "owner", { company: "kong", evidenceRunId: "unrelated" })).status, 422);
  assert.equal((await request(`/api/agent-company/orders/${order.id}/done`, "owner", { company: "kong" })).status, 200);
  assert.equal((await request("/api/agent-council/run", "owner", {})).status, 200);
  assert.equal(cycles, 1);
});
